/** 把題幹拆成情境與（1）（2）小題 */
export function splitQuestion(question: string) {
  const [stem, ...rest] = question.split(/(?=（\d）)/);
  return { stem: stem.trim(), parts: rest.map(p => p.trim()) };
}

/** 依（1）（2）把答題要點分組 */
export function groupPoints(points: string[]) {
  const groups: { label: string; items: string[] }[] = [];
  for (const point of points) {
    const m = point.match(/^（(\d)）/);
    const label = m ? `（${m[1]}）` : "";
    const text = m ? point.slice(m[0].length) : point;
    const last = groups[groups.length - 1];
    if (last && last.label === label) last.items.push(text);
    else groups.push({ label, items: [text] });
  }
  return groups;
}
